window.getResult = function (scores) {
  var maxKey = null;
  var maxVal = -Infinity;
  for (var k in scores) {
    if (scores.hasOwnProperty(k) && scores[k] > maxVal) {
      maxVal = scores[k];
      maxKey = k;
    }
  }

  var result = window.RESULTS[maxKey];
  return {
    key: maxKey,
    name: result.name,
    emoji: result.emoji,
    description: result.description,
    detail: result.detail,
    traits: result.traits,
    strengths: result.strengths,
    weaknesses: result.weaknesses,
    good: result.good,
    bad: result.bad,
  };
};
